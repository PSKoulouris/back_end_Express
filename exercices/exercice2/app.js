const express = require('express')
const app = express()

const dbConnection = require ('./data/database') 

const routes = require('./routes/routes')

///////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////

app.use(express.json())
app.use('/', routes)

/////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////

dbConnection.initializeDb()
    .then(function(){
        app.listen(3000)
    })
    .catch (function(){
        console.log("database connection failed")}
    )

    
